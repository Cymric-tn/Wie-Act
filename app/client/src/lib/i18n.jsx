// Engine-backed feature strings override the earlier placeholders (e.g. the suggestion chips).
const DICTIONARIES = { en: { ...en, ...AI.en }, fr: { ...fr, ...AI.fr }, ar: { ...ar, ...AI.ar } };

const LanguageContext = createContext(null);

function initialLanguage() {
  const saved = readStored("ednova-lang", "");
  if (DICTIONARIES[saved]) return saved;
  const browser = (navigator.language || "en").slice(0, 2);
  return DICTIONARIES[browser] ? browser : "en";
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(initialLanguage);
  const meta = LANGUAGES.find((l) => l.id === lang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = meta.dir;
    store("ednova-lang", lang);
  }, [lang, meta.dir]);

  const value = useMemo(() => {
    const dict = DICTIONARIES[lang];
    const t = (key, vars) => {
      let text = dict[key] ?? DICTIONARIES.en[key] ?? key;
      if (vars) Object.entries(vars).forEach(([k, v]) => { text = text.replaceAll(`{${k}}`, v); });
      return text;
    };
    return { lang, setLang, dir: meta.dir, t, languageName: meta.name };
  }, [lang, meta]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}

/** Segmented FR / EN / AR control. */
export function LanguageSwitcher({ className = "" }) {
  const { lang, setLang } = useI18n();
  return (
    <div className={`lang-switch ${className}`} role="radiogroup" aria-label="Language">
      {LANGUAGES.map((l) => (
        <button
          key={l.id}
          role="radio"
          aria-checked={lang === l.id}
          className={lang === l.id ? "active" : ""}
          onClick={() => setLang(l.id)}
          title={l.name}
          lang={l.id}
        >
          {l.label}
        </button>
      ))}
    </div>
  );
}

