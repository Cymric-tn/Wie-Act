TOKEN = "service-token-for-tests"
AUTH = {S.TOKEN_HEADER: TOKEN}
JSON_REPLY = json.dumps({"intent": "EXPLAIN", "language": "FRENCH", "confusion": "LOW", "complexity": 2, "confidence": 0.9,
                         "verdict": "SUPPORTED", "correction": "", "keep": [1]})


@pytest.fixture(autouse=True, scope="module")
def _index(tmp_path_factory):
    """make_engine reads test_engine.INDEX: a real index of data/docs, so explain is grounded for real."""
    test_engine.INDEX = str(tmp_path_factory.mktemp("idx") / "chunks.json")
    save_chunks(test_engine.INDEX, chunk_dir("data/docs"))


def scripted_provider(body):
    """What the model would say, by model class and mode: enough for every task's guards to pass."""
    if body["model"] == "deepseek-ocr":
        return chat_ok("f'(x) = 6x + 5", 820, 40)
    if body.get("response_format"):
        return chat_ok(JSON_REPLY, 120, 30)
    return chat_ok("Quelle règle donne la dérivée de xⁿ ? Regarde l'exposant.", 120, 30)


CASES = [
    ("classify", {"message": "c'est quoi une dérivée ?"}),
    ("hint", {"problem": "Dérive f(x) = 3x² + 5x"}),
    ("explain", {"question": "C'est quoi le nombre dérivé ?"}),
    ("quiz", {"message": "donne moi un exercice sur la tangente", "intro": False}),
    ("grade", {"problem": "Dérive f(x) = x²", "solution": "2x", "attempt": "2x"}),
    ("compress", {"question": "dérivée constante",
                  "chunks": [{"chunk_id": "a", "text": "H — S\nLa dérivée d'une constante est 0. Le ciel est bleu."}]}),
    ("ocr_transcribe", {"image": data_url(photo())}),
    ("check_claim", {"claim": "(x³)' = x²"}),                                       # sympy settles it: no request
    ("check_answer", {"problem": "Dérive f(x) = x⁴", "exercise_id": "d01", "steps": ["f(x) = x⁴", "f'(x) = x³"]}),
    ("prep_plan", {"scope": {"unit_ids": ["derivees"]}, "deadline": "2099-01-01", "pace_min_per_day": 45}),
]


def client(app):
    return httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url="http://127.0.0.1", headers=AUTH)


@pytest.mark.parametrize("task,inputs", CASES, ids=[c[0] for c in CASES])
async def test_run_each_task_through_the_service_with_the_real_engine(vt, task, inputs):
    eng, fake, _ = make_engine(vt, scripted_provider)
    async with client(S.create_app(eng, token=TOKEN)) as c:
        r = await c.post("/run", json={"task": task, "inputs": inputs, "context": {"language": "FRENCH", "learner_id": "L1"}})
    d = r.json()
    assert r.status_code == 200, d
    assert d["task"] == task and d["events"] and d["request_id"] and d["latency_ms"] >= 0
    assert d["text"] or d["data"]
    if task in ("check_claim", "prep_plan", "check_answer", "grade", "quiz"):
        assert d["model_class_used"] is None or d["model_class_used"] == "compact"
    if task == "check_claim":
        assert d["data"]["verdict"] == "CONTRADICTED" and d["data"]["checked_by"] == "sympy" and fake.requests == []
    if task == "prep_plan":
        assert d["data"]["focus_points"] and fake.requests == []
    if task == "explain":                                         # grounded in the course index and generated by mid-size
        assert d["model_class_used"] == "midsize" and "no_relevant_context" not in [e["name"] for e in d["events"]]
        assert d["notes"]["sources"]
    if task == "ocr_transcribe":
        assert d["model_class_used"] == "vision" and "resizing_image" in [e["name"] for e in d["events"]]
    assert not d["degraded"], d["degrade_reason"]


async def test_stream_with_the_real_engine_sends_the_engines_own_events_then_the_result(vt):
    eng, _, _ = make_engine(vt, scripted_provider)
    async with ASGIWebSocket(S.create_app(eng, token=TOKEN), AUTH) as ws:
        assert ws.accepted
        await ws.send({"task": "hint", "inputs": {"problem": "Dérive f(x) = 3x² + 5x"}, "context": {"language": "FRENCH"}})
        frames = await ws.frames()
    events = [f["event"]["name"] for f in frames if f["type"] == "event"]
    result = next(f["result"] for f in frames if f["type"] == "result")
    assert events == [e["name"] for e in result["events"]] and "generating" in events
    assert result["task"] == "hint" and result["model_class_used"] == "compact" and frames[-1]["code"] == 1000


async def test_a_repeat_through_the_service_is_a_cache_hit_and_can_be_invalidated(vt):
    eng, fake, _ = make_engine(vt, scripted_provider)
    body = {"task": "hint", "inputs": {"problem": "Dérive f(x) = 3x² + 5x"}, "context": {"language": "FRENCH"}}
    async with client(S.create_app(eng, token=TOKEN)) as c:
        first = (await c.post("/run", json=body)).json()
        again = (await c.post("/run", json=body)).json()
        removed = (await c.post("/cache/invalidate", json={"request_id": first["request_id"]})).json()["removed"]
        third = (await c.post("/run", json=body)).json()
    assert [again["from_cache"], removed, third["from_cache"]] == [True, 1, False] and len(fake.requests) == 2
